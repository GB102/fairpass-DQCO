"""Step 11: generate docs/DATA_MANIFEST.md from the files actually on disk (counts, periods, checksums)."""
import glob
import hashlib
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()[:16]


def main():
    st = {s["id"]: s for s in json.load(open(ROOT / "data/raw/satnogs_stations.json", encoding="utf-8"))}
    rows = []
    for p in sorted(glob.glob(str(ROOT / "data/raw/obs/*.json"))):
        obs = json.load(open(p, encoding="utf-8"))
        name = Path(p).stem
        period, gs = name.split("_")
        c = Counter(o["status"] for o in obs)
        starts = sorted(o["start"] for o in obs)
        rows.append((period, int(gs), len(obs), c.get("good", 0), c.get("bad", 0), c.get("failed", 0),
                     c.get("unknown", 0), starts[0][:16] if starts else "", starts[-1][:16] if starts else "",
                     len({o["norad_cat_id"] for o in obs}), sha(p)))
    pv = json.load(open(ROOT / "results/pass_validation.json")) if (ROOT / "results/pass_validation.json").exists() else {}
    eff = pv.get("effective_horizon_deg", {})
    L = []
    L.append("# Data manifest\n")
    L.append("Generated by `scripts/11_manifest.py` from the files on disk. Every raw HTTP response is also logged with its "
             "URL, UTC fetch time and SHA-256 in `data/cache/provenance.jsonl`. The cache itself is not committed.\n")
    L.append("## Sources and licences\n")
    L.append("| Source | What we use | Licence / terms | Accessed |\n|---|---|---|---|")
    L.append("| SatNOGS Network API `/api/observations/` | per-observation station, coordinates, start/end, stored TLE, "
             "max elevation, transmitter mode/baud, vetted status, demodulated-frame count | CC BY-SA 4.0 "
             "(Libre Space Foundation; station owners license submitted results under CC BY-SA) | 2026-10-10 |")
    L.append("| SatNOGS Network API `/api/stations/` | station location, altitude, configured horizon, antennas | "
             "CC BY-SA 4.0 | 2026-10-10 |")
    L.append("| SatNOGS DB API `/api/satellites/`, `/api/transmitters/` | satellite names, transmitter modes | "
             "CC BY-SA 4.0 | 2026-10-10 |")
    L.append("| TLEs | taken from the SatNOGS observation records (`tle_source` mostly Space-Track.org via SatNOGS); "
             "no CelesTrak download was needed for the retrospective day | redistributed by SatNOGS under CC BY-SA 4.0 | "
             "2026-10-10 |")
    L.append("\nThe derived files in `data/processed/` and `demo/qollab/data/` are adaptations of the SatNOGS data and are "
             "shared under **CC BY-SA 4.0** with this attribution. They are not covered by the MIT licence of the code.\n")
    L.append("## Observation extracts (`data/raw/obs/`)\n")
    L.append("Columns kept: id, start, end, ground_station, norad_cat_id, status, waterfall_status, vetted_status, "
             "max_altitude, rise/set azimuth, transmitter uuid/mode/baud/downlink, tle0-2, tle_source, station "
             "lat/lng/alt, observation_frequency, n_demod.\n")
    L.append("| period | station | name | obs | good | bad | failed | unknown | first start (UTC) | last start | "
             "satellites | config horizon | effective horizon | sha256[:16] |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        s = st.get(r[1], {})
        L.append(f"| {r[0]} | {r[1]} | {s.get('name', '')} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} | "
                 f"{r[8]} | {r[9]} | {s.get('min_horizon', '')} | {eff.get(str(r[1]), '')} | {r[10]} |")
    L.append("\n## What each kind of value is\n")
    L.append("| kind | examples |\n|---|---|")
    L.append("| **measured** (third-party records) | vetted good/bad outcome of each observation, observation start/end, "
             "SatNOGS-recorded max elevation |")
    L.append("| **computed** (deterministic from measured inputs) | SGP4 pass windows and max elevation from stored TLEs, "
             "effective station horizons |")
    L.append("| **fitted** | pass-success model parameters and 40 bootstrap replicates (`results/link_model.json`) |")
    L.append("| **simulated** | schedules and their expected delivered data, QAOA output distributions (noiseless and "
             "Aer density-matrix noise), LNS traces |")
    L.append("| **hypothetical** | equal mission priority weights (no public priorities exist), fairness weight λ, "
             "target K = 2 contacts/day, 60 s re-pointing gap, IonQ-like noise levels |")
    L.append("\n## Known gaps and caveats\n")
    L.append("* 'good'/'bad' is a vetting label (signal in the waterfall or decoded data), not a byte count. Only a "
             "minority of good observations upload demodulated frames, so frame counts are not used as data volume.")
    L.append("* 'unknown' (not yet vetted) and 'failed' (station/software failure) observations are excluded from the "
             "success model. Vetting may be biased towards observations a human looked at.")
    L.append("* Expected data volume uses the transmitter baud rate times pass duration as a link-capacity proxy. "
             "Broadcast beacons do not transmit continuously. The sensitivity analysis replaces it with contact time.")
    L.append("* Station configuration (horizon) is a live snapshot. The horizon the scheduler actually used is "
             "inferred from each station's own observations.")
    L.append("* Ten European stations were selected by record length and geography, not at random. Results describe "
             "this sub-network.")
    (ROOT / "docs/DATA_MANIFEST.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/DATA_MANIFEST.md with", len(rows), "observation files")


if __name__ == "__main__":
    main()
